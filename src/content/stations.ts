export function buildCampaignRoute(campaignLength: CampaignLength): StationRecord[] {
  const selectedIds = STRATIFIED_STATION_IDS[campaignLength] || STRATIFIED_STATION_IDS[10];
  const learningStations = selectedIds
    .map((id) => LEARNING_STATIONS_POOL.find((s) => s.station_id === id))
    .filter((s): s is StationRecord => Boolean(s));

  const route: StationRecord[] = [];
  let checkpointCounter = 0;
  const checkpointKeys = ['CP_A', 'CP_B', 'CP_C'];

  learningStations.forEach((st, idx) => {
    const learningIndex = idx + 1;
    route.push({
      ...st,
      order: route.length + 1,
    });

    // Insert a synthesis checkpoint after every 5 learning stations
    if (learningIndex % 5 === 0) {
      const templateKey = checkpointKeys[Math.min(checkpointCounter, checkpointKeys.length - 1)];
      const template = CHECKPOINT_TEMPLATES[templateKey];
      checkpointCounter += 1;
      const cpId = `CP_0${checkpointCounter}`;
      route.push({
        ...template,
        station_id: cpId,
        order: route.length + 1,
        title: `Checkpoint ${checkpointCounter}: Tổng hợp chặng ${learningIndex - 4}–${learningIndex}`,
        track_config: {
          ...template.track_config,
          checkpoint_id: cpId,
        },
      });
    }
  });

  return route;
}
