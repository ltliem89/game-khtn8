/**
 * Helper to look up the international English pronunciation item for a given Physics station quantity ID.
 */
export function getPronunciationByQuantityId(quantityId: string): ChemicalSubstanceItem | undefined {
  if (quantityId === 'PHY_LEVER') {
    return FAMILIAR_ELEMENTS_AND_COMPOUNDS.find((item) => item.id === 'phy_moment_lever_si');
  }
  if (quantityId === 'PHY_VOLTAGE') {
    return FAMILIAR_ELEMENTS_AND_COMPOUNDS.find((item) => item.id === 'phy_current_voltage_si');
  }
  if (
    quantityId === 'PHY_JOULEMETER' ||
    quantityId === 'PHY_HEAT_TRANSFER' ||
    quantityId === 'PHY_THERMAL_EXPANSION'
  ) {
    return FAMILIAR_ELEMENTS_AND_COMPOUNDS.find((item) => item.id === 'phy_thermal_energy_si');
  }
  return FAMILIAR_ELEMENTS_AND_COMPOUNDS.find((item) => item.relatedQuantityId === quantityId);
}

/**
 * Formats an item into clean international English speech text for Web Speech API.
 */
export function buildInternationalSpeechText(
  item: ChemicalSubstanceItem,
  includeSentence = true
): string {
  if (includeSentence) {
    return `${item.englishName}. ${item.spokenFormulaEn}. ${item.englishSentence}`;
  }
  return `${item.englishName}. ${item.spokenFormulaEn}.`;
}
